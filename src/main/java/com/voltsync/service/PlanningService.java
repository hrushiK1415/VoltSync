package com.voltsync.service;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.voltsync.common.AppException;
import com.voltsync.common.ErrorCode;
import com.voltsync.controller.dto.SolveRequest;
import com.voltsync.controller.dto.SolveResponse;
import com.voltsync.domain.*;
import com.voltsync.engine.GreedyLocalSearchSolver;
import com.voltsync.engine.PlanValidator;
import com.voltsync.engine.Solver;
import com.voltsync.repository.PlanEntity;
import com.voltsync.repository.PlanRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.cache.annotation.CachePut;
import org.springframework.cache.annotation.Cacheable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Duration;
import java.util.List;
import java.util.UUID;

@Service
@Transactional
public class PlanningService {

    private static final Logger log = LoggerFactory.getLogger(PlanningService.class);

    private final FleetService fleetService;
    private final PlanRepository planRepository;
    private final ObjectMapper objectMapper;
    private final Solver solver = new GreedyLocalSearchSolver();
    private final PlanValidator validator = new PlanValidator();

    public PlanningService(FleetService fleetService,
                           PlanRepository planRepository,
                           ObjectMapper objectMapper) {
        this.fleetService = fleetService;
        this.planRepository = planRepository;
        this.objectMapper = objectMapper;
    }

    public SolveResponse solveShift(SolveRequest request) {
        String planId = "PLAN-" + UUID.randomUUID().toString().substring(0, 8);
        log.info("Starting shift solver for planId={}", planId);

        List<Vehicle> vehicles = fleetService.getAllVehiclesDomain();
        List<Hub> hubs = fleetService.getAllHubsDomain();
        List<Trip> trips = fleetService.getAllTripsDomain();

        if (vehicles.isEmpty() || trips.isEmpty()) {
            throw new AppException(ErrorCode.INVALID_INPUT, "Fleet or trips database is empty. Load input data first.");
        }

        Duration timeBudget = Duration.ofSeconds(
                (request != null && request.timeBudgetSeconds() != null && request.timeBudgetSeconds() > 0)
                        ? request.timeBudgetSeconds() : 15
        );

        Solver.SolverInput solverInput = new Solver.SolverInput(
                planId, vehicles, hubs, trips,
                Tariff.defaultTariff(),
                ConsumptionModel.defaultModel(),
                timeBudget
        );

        long start = System.currentTimeMillis();
        Plan plan = solver.solve(solverInput);
        long solveTimeMs = System.currentTimeMillis() - start;

        ValidationReport report = validator.validate(plan, vehicles, hubs, trips);
        if (!report.valid()) {
            log.error("Plan {} generated by solver failed independent validator with {} violations",
                    planId, report.violations().size());
        }

        try {
            String json = objectMapper.writeValueAsString(plan);
            PlanEntity entity = new PlanEntity(
                    plan.getPlanId(), plan.getVersion(), plan.getCost(),
                    plan.getLowerBound(), plan.getUnassigned().size(), json
            );
            planRepository.save(entity);
        } catch (JsonProcessingException e) {
            log.error("Failed to serialize plan to JSON", e);
            throw new AppException(ErrorCode.INTERNAL_ERROR, "Failed to serialize plan", e);
        }

        return new SolveResponse(
                plan.getPlanId(), plan.getVersion(), plan.getCost(),
                plan.getLowerBound(), plan.getOptimalityGap(),
                plan.getUnassigned().size(), solveTimeMs
        );
    }

    @Transactional(readOnly = true)
    @Cacheable(value = "plans", key = "#planId")
    public Plan getPlan(String planId) {
        PlanEntity entity = planRepository.findById(planId)
                .orElseThrow(() -> new AppException(ErrorCode.PLAN_NOT_FOUND, "Plan " + planId + " not found"));

        try {
            return objectMapper.readValue(entity.getPlanJson(), Plan.class);
        } catch (JsonProcessingException e) {
            log.error("Failed to parse plan JSON for planId={}", planId, e);
            throw new AppException(ErrorCode.INTERNAL_ERROR, "Failed to parse plan JSON", e);
        }
    }

    @Transactional(readOnly = true)
    public ValidationReport getValidationReport(String planId) {
        Plan plan = getPlan(planId);
        List<Vehicle> vehicles = fleetService.getAllVehiclesDomain();
        List<Hub> hubs = fleetService.getAllHubsDomain();
        List<Trip> trips = fleetService.getAllTripsDomain();

        return validator.validate(plan, vehicles, hubs, trips);
    }

    @Transactional(readOnly = true)
    public List<UnassignedTrip> getUnassignedTrips(String planId) {
        Plan plan = getPlan(planId);
        return plan.getUnassigned();
    }

    @Transactional(readOnly = true)
    public List<Event> getVehicleTimeline(String planId, String vehicleId) {
        Plan plan = getPlan(planId);
        List<Event> timeline = plan.getScheduleForCab(vehicleId);
        if (timeline == null || timeline.isEmpty()) {
            fleetService.getAllVehiclesDomain().stream()
                    .filter(v -> v.getId().equals(vehicleId))
                    .findFirst()
                    .orElseThrow(() -> new AppException(ErrorCode.VEHICLE_NOT_FOUND, "Vehicle " + vehicleId + " not found"));
        }
        return timeline;
    }

    @CachePut(value = "plans", key = "#plan.planId")
    public Plan updatePlan(Plan plan) {
        try {
            String json = objectMapper.writeValueAsString(plan);
            PlanEntity entity = planRepository.findById(plan.getPlanId())
                    .orElse(new PlanEntity(plan.getPlanId(), plan.getVersion(), plan.getCost(), plan.getLowerBound(), plan.getUnassigned().size(), json));
            entity.setVersion(plan.getVersion());
            entity.setCost(plan.getCost());
            entity.setLowerBound(plan.getLowerBound());
            entity.setUnassignedCount(plan.getUnassigned().size());
            entity.setPlanJson(json);
            planRepository.save(entity);
            return plan;
        } catch (JsonProcessingException e) {
            throw new AppException(ErrorCode.INTERNAL_ERROR, "Failed to serialize plan", e);
        }
    }
}
